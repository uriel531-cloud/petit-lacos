/** Modelos para "Adicionar seção" no construtor da Home. */
export function createSection(type: HomeSection["type"]): HomeSection {
  const template = DEFAULT_SECTIONS.find((s) => s.type === type);
  if (template) return { ...structuredClone(template), id: newId("sec"), active: true };
  // "newsletter" e outros sempre existem nos defaults; fallback defensivo:
  return { ...structuredClone(DEFAULT_SECTIONS[0]!), id: newId("sec") };
}

export function createHeroSlide(): HeroSlide {
  return {
    ...structuredClone(DEFAULT_HERO_SLIDE),
    id: newId("slide"),
    title: "Novo slide",
    rotatingWords: [],
    textEffect: "fade",
  };
}
